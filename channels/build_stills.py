#!/usr/bin/env python3
"""Grab a fresh frame from each channel for Tony's tiles ("live stills").

    channels/.venv/bin/python channels/build_stills.py                      # Lebanon + Australia + Arabic + Movies rows
    channels/.venv/bin/python channels/build_stills.py --files countries/usa.json rows/arabic.json
    channels/.venv/bin/python channels/build_stills.py --publish            # also force-push to the `stills` branch

Each still is centre-cropped to 16:9 after removing black letterbox/pillarbox bars, scaled to
480×270 and saved as stills/<channel id>.jpg. The app loads them from
https://raw.githubusercontent.com/clnnhtrn/tony-tv/stills/stills/<id>.jpg and falls back to the
logo-on-colour tile if a still is missing. The `stills` branch is an orphan branch with a single
commit, replaced on every publish, so images never pile up in the repo's history.
"""
import argparse
import concurrent.futures as cf
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image, ImageOps

HERE = Path(__file__).resolve().parent
DIST = HERE / "dist"
OUT = HERE / ".stills"
DEFAULT = ["countries/lebanon.json", "countries/australia.json", "rows/arabic.json", "rows/movies.json"]


def ffmpeg():
    exe = shutil.which("ffmpeg")
    if exe:
        return exe
    import imageio_ffmpeg  # bundled binary (pip install imageio-ffmpeg)
    return imageio_ffmpeg.get_ffmpeg_exe()


def grab(ch, ff, tmp):
    raw = Path(tmp) / f"{ch['id']}.raw.jpg"
    for url in [ch["url"]] + ch.get("backupUrls", []):
        hdrs = ch.get("headers") or {} if url == ch["url"] else {}
        cmd = [ff, "-y", "-loglevel", "error", "-rw_timeout", "12000000"]
        ua = next((v for k, v in hdrs.items() if k.lower() == "user-agent"), None)
        ref = next((v for k, v in hdrs.items() if k.lower() == "referer"), None)
        if ua:
            cmd += ["-user_agent", ua]
        if ref:
            cmd += ["-headers", f"Referer: {ref}\r\n"]
        cmd += ["-i", url, "-ss", "2", "-frames:v", "1", "-vf", "scale=960:-2", "-q:v", "4", str(raw)]
        try:
            subprocess.run(cmd, capture_output=True, timeout=40)
        except subprocess.TimeoutExpired:
            continue
        if raw.exists() and raw.stat().st_size > 6000:
            return raw
    return None


def finish(raw, dest):
    im = Image.open(raw).convert("RGB")
    mask = ImageOps.grayscale(im).point(lambda v: 255 if v > 22 else 0)
    box = mask.getbbox()
    if not box:
        return False  # all black: skip (better the logo tile than a black tile)
    im = im.crop(box)
    w, h = im.size
    tw, th = min(w, int(h * 16 / 9)), min(h, int(w * 9 / 16))
    l, t = (w - tw) // 2, (h - th) // 2
    im = im.crop((l, t, l + tw, t + th)).resize((480, 270), Image.LANCZOS)
    im.save(dest, quality=78, optimize=True, progressive=True)
    return True


def publish():
    """Force-push .stills/ as a single-commit orphan branch `stills`."""
    repo = HERE.parent
    remote = subprocess.run(["git", "-C", str(repo), "remote", "get-url", "origin"], capture_output=True, text=True).stdout.strip()
    with tempfile.TemporaryDirectory() as d:
        # Start from the stills already published, then overlay the new ones: a channel we couldn't
        # reach this time (e.g. Australia-only streams from a US server) keeps its last good still.
        prev = Path(d) / "prev"
        if subprocess.run(["git", "clone", "-q", "--depth", "1", "-b", "stills", remote, str(prev)], capture_output=True).returncode == 0:
            shutil.copytree(prev / "stills", Path(d) / "stills", dirs_exist_ok=True)
        shutil.copytree(OUT, Path(d) / "stills", dirs_exist_ok=True)
        shutil.rmtree(prev, ignore_errors=True)
        (Path(d) / "README.md").write_text("Live stills for Tony's tiles. Generated by channels/build_stills.py; replaced on every run.\n")
        g = lambda *a: subprocess.run(["git", "-C", d, *a], check=True, capture_output=True)
        g("init", "-q", "-b", "stills")
        g("add", "-A")
        g("-c", "user.name=Tony stills", "-c", "user.email=stills@users.noreply.github.com", "commit", "-q", "-m", "Live stills")
        g("push", "-q", "--force", remote, "stills")
    print("Published to the stills branch")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--files", nargs="*", default=DEFAULT)
    ap.add_argument("--publish", action="store_true")
    ap.add_argument("--workers", type=int, default=10)
    args = ap.parse_args()
    chans = {}
    for f in args.files:
        for c in json.loads((DIST / f).read_text())["channels"]:
            if c.get("media") in ("video", None) and c.get("status") in ("ok", "untested", "geoblocked"):
                chans[c["id"]] = c
    OUT.mkdir(exist_ok=True)
    ff = ffmpeg()
    ok = 0
    with tempfile.TemporaryDirectory() as tmp, cf.ThreadPoolExecutor(args.workers) as pool:
        for c, raw in zip(chans.values(), pool.map(lambda c: grab(c, ff, tmp), chans.values())):
            if raw and finish(raw, OUT / f"{c['id']}.jpg"):
                ok += 1
    print(f"Stills: {ok}/{len(chans)} channels")
    if args.publish:
        publish()


if __name__ == "__main__":
    main()
